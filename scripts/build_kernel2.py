"""Build the self-contained Kaggle kernel for the class-2 fusion submission.

Kaggle code competitions run one code file with the competition data mounted
read-only and no internet, so the whole serving pipeline is embedded into a
single kernel.py as base64 payloads (scripts/build_kernel.py's pattern). What
does NOT fit in a kernel file — and what the attached private dataset
`<username>/enveda-class2-serve` provides at /kaggle/input — is:

    train_clean.parquet              the cleaned train data the model used
    cache/{molecules.parquet,         the molecule-key cache the model was
    row_key.npy, fps.npy, fps.hash}  trained with (READ only at serve time)
    denovo_v1.pt + denovo_fp_head.pt channel-P v2 artifacts (guarded load)
    difficulty2_stage2_model.joblib  the fusion model (box run, F2-off)
    formulas.parquet                 pre-seeds the RDKit formula cache
    rdkit-*.whl                      Kaggle's image ships no RDKit; the
                                     kernel pip-installs it offline

At runtime the kernel writes the repo layout under WORK/app, installs RDKit
from the dataset wheels, seeds the formula cache, and runs
max_class2_exp/predict_test.py on the mounted test.parquet (pool = train
structures, channels in-silico/metfrag live, channel P v2 from the dataset,
F2 off — the exact configuration the shipped fusion model was trained in).

Usage (from the repo root, after the box artifacts are rsynced home):
    uv run python scripts/build_kernel2.py [--kernel-dir ../kernels/casmi26-class2-sub]

The output dir gets kernel.py + kernel-metadata.json; push it with the Kaggle
CLI or the omac sidecar (POST /kernels/push), then submit the finished version
with scripts/submit_kernel.py --kernel <owner>/casmi26-class2-sub.
"""

import argparse
import base64
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

# repo-relative path -> runtime path inside WORK/app (the class-2 serving
# closure: predict_test + features + channels + the dataset-creation cache/
# cleaning modules + the src modules they import; no stage2/train code ships)
PAYLOADS = {
    "dataset-creation/common.py": "dataset-creation/common.py",
    "dataset-creation/dataloader.py": "dataset-creation/dataloader.py",
    "max_class2_exp/annotations.py": "max_class2_exp/annotations.py",
    "max_class2_exp/features.py": "max_class2_exp/features.py",
    "max_class2_exp/fpchannel.py": "max_class2_exp/fpchannel.py",
    "max_class2_exp/insilico.py": "max_class2_exp/insilico.py",
    "max_class2_exp/metfrag.py": "max_class2_exp/metfrag.py",
    "max_class2_exp/pool.py": "max_class2_exp/pool.py",
    "max_class2_exp/predict_test.py": "max_class2_exp/predict_test.py",
    "max_class2_exp/spectra_utils.py": "max_class2_exp/spectra_utils.py",
    "max_class2_exp/speclib.py": "max_class2_exp/speclib.py",
    "src/enveda_casmi26/__init__.py": "src/enveda_casmi26/__init__.py",
    "src/enveda_casmi26/fp_model.py": "src/enveda_casmi26/fp_model.py",
    "src/enveda_casmi26/pipeline.py": "src/enveda_casmi26/pipeline.py",
    "src/enveda_casmi26/fragmentation.py": "src/enveda_casmi26/fragmentation.py",
}

TEMPLATE = '''#!/usr/bin/env python
"""Kaggle kernel: class-2 fusion submission for Enveda CASMI 2026.

Class-2 pipeline: candidates = train structures within ±8.5 ppm of the query
mass, re-ranked by the trained fusion model (logistic/HGB over in-silico,
metfrag-lite and channel-P v2 features; the visibility/source block is
dropped). Molecules with fewer than 25 candidates are padded with the
mass-nearest structures. Channel F2 (ICEBERG) is off in serving — the shipped
model was trained in the same configuration on the GPU box.

Generated by scripts/build_kernel2.py — do not edit by hand. The pipeline
modules are embedded as base64 below and unpacked to WORK/app; train, the
molecule-key cache, the channel-P v2 artifacts and the fusion model come from
the attached enveda-class2-serve dataset; predict_test.py runs on the mounted
test.parquet and writes WORK/submission.csv.

Smoke test locally:
    KERNEL_WORK=/tmp/kw KERNEL_COMP_DIR=data KERNEL_ART_DIR=<staged dataset> \\
        python kernels/casmi26-class2-sub/kernel.py
"""
import base64
import glob
import os
import subprocess
import sys
import time
from pathlib import Path

WORK = Path(os.environ.get("KERNEL_WORK", "/kaggle/working"))
COMP = os.environ.get("KERNEL_COMP_DIR")
ART = os.environ.get("KERNEL_ART_DIR")
T0 = time.time()


def log(msg):
    print(msg, flush=True)


def find(name):
    hits = glob.glob(f"/kaggle/input/**/{{name}}", recursive=True)
    return sorted(hits, key=len)[0] if hits else None


PAYLOADS = {{
{payloads}
}}


def ensure_rdkit(art: Path):
    """Kaggle's image ships no RDKit; install it offline from the dataset wheels."""
    try:
        import rdkit  # noqa: F401
        log("[kernel] rdkit already present in the image")
        return
    except ImportError:
        pass
    wheels = sorted(glob.glob(str(art / "*.whl")))
    if not wheels:
        raise SystemExit("[kernel] no rdkit in the image and no *.whl in the artifacts "
                         "dataset — add the rdkit wheel(s) to enveda-class2-serve")
    log(f"[kernel] installing rdkit offline: {{[Path(w).name for w in wheels]}}")
    target = Path("/tmp") / "pylibs"        # NOT /kaggle/working: a ~500MB install
    for w in wheels:                       # would blow the kernel output save
        subprocess.run([sys.executable, "-m", "pip", "install", "--no-index", "--no-deps",
                        "--target", str(target), w], check=True)
    sys.path.insert(0, str(target))
    import rdkit  # noqa: F401  (a wheel for a different python would fail here)
    log(f"[kernel] rdkit {{rdkit.__version__}} installed from the dataset")


def main():
    log(f"[kernel] working dir: {{WORK}}")
    test_path = find("test.parquet")
    if test_path is None:
        raise SystemExit("test.parquet not found under /kaggle/input")
    comp = COMP or str(Path(test_path).parent)
    test = os.path.join(comp, "test.parquet")
    log(f"[kernel] competition data: {{comp}}")

    if ART is None:
        train_clean = find("train_clean.parquet")
        if train_clean is None:
            raise SystemExit("train_clean.parquet not found under /kaggle/input — attach "
                             "the enveda-class2-serve dataset to the kernel")
        art = Path(train_clean).parent
    else:
        art = Path(ART)
    log(f"[kernel] artifacts dataset: {{art}}")
    need = ["train_clean.parquet", "denovo_fp_head.pt", "difficulty2_stage2_model.joblib",
            "cache/molecules.parquet", "cache/row_key.npy"]
    missing = [n for n in need if not (art / n).exists()]
    if missing:
        raise SystemExit(f"[kernel] missing from the artifacts dataset: {{missing}}")
    if not any((art / n).exists() for n in ("denovo_v1.pt", "denovo_v1.pt.last.pt")):
        raise SystemExit("[kernel] no denovo_v1.pt[.last.pt] in the artifacts dataset")

    ensure_rdkit(art)

    app = WORK / "app"
    for rel, payload in PAYLOADS.items():
        p = app / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(base64.b64decode(payload))
    log(f"[kernel] unpacked {{len(PAYLOADS)}} files to {{app}}")

    # pre-seed the formula cache (RDKit CalcMolFormula over ~250k structures
    # would otherwise cost a few kernel minutes on first run)
    if (art / "formulas.parquet").exists():
        dst = app / "max_class2_exp" / "out" / "cache" / "formulas.parquet"
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes((art / "formulas.parquet").read_bytes())
        log("[kernel] seeded the formula cache from the dataset")

    sys.path.insert(0, str(app / "max_class2_exp"))
    import predict_test
    sys.argv = ["predict_test",
                "--train", str(art / "train_clean.parquet"),
                "--test", test,
                "--cache-dir", str(art / "cache"),
                "--artifacts", str(art),
                "--model", str(art / "difficulty2_stage2_model.joblib"),
                "--out", str(WORK / "submission.csv"),
                "--diag", str(WORK / "predict_diag.parquet")]
    predict_test.main()

    import pandas as pd
    sub = pd.read_csv(WORK / "submission.csv")
    n_slots = sub["smiles"].str.count(";") + 1
    log(f"[kernel] submission.csv: {{len(sub)}} molecules, slots min {{n_slots.min()}} "
        f"/ median {{n_slots.median():.0f}} / max {{n_slots.max()}}")
    log(f"[kernel] done in {{time.time() - T0:.0f}s")


if __name__ == "__main__":
    main()
'''

METADATA = '''{{
  "id": "{username}/casmi26-class2-sub",
  "title": "casmi26-class2-sub",
  "code_file": "kernel.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_tpu": false,
  "enable_internet": false,
  "dataset_sources": ["{username}/enveda-class2-serve"],
  "competition_sources": ["enveda-CASMI26-molecule-id-mass-spectra"],
  "kernel_sources": []
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kernel-dir", type=Path,
                        default=PROJECT_ROOT.parent / "kernels" / "casmi26-class2-sub",
                        help="output dir (kernel.py + kernel-metadata.json)")
    parser.add_argument("--username", default="mmaxdietsch", help="Kaggle username for the ids")
    args = parser.parse_args()

    lines, total = [], 0
    for src, rel in PAYLOADS.items():
        blob = base64.b64encode((PROJECT_ROOT / src).read_bytes()).decode()
        total += len(blob)
        lines.append(f'    "{rel}": (\n')
        # wrap the base64 at 96 chars to keep the file diff-able
        for i in range(0, len(blob), 96):
            lines.append(f'        "{blob[i:i + 96]}"\n')
        lines.append('    ),\n')
    kernel = TEMPLATE.format(payloads="".join(lines))
    args.kernel_dir.mkdir(parents=True, exist_ok=True)
    (args.kernel_dir / "kernel.py").write_text(kernel)
    (args.kernel_dir / "kernel-metadata.json").write_text(
        METADATA.format(username=args.username))
    print(f"wrote {args.kernel_dir}/kernel.py ({len(kernel) / 1024:.0f} KiB, "
          f"payloads {total / 1024:.0f} KiB) and kernel-metadata.json")
    print("next: stage the enveda-class2-serve dataset (see max_class2_exp/README.md "
          "'Serving'), push the kernel, then scripts/submit_kernel.py "
          f"--kernel {args.username}/casmi26-class2-sub")


if __name__ == "__main__":
    main()
