"""Build the self-contained Kaggle kernel for the stage-2 submission.

Kaggle code competitions run one code file with the competition data mounted
read-only and no internet, so the whole pipeline (the max_class1_exp modules,
the dataset-creation cache builder and the trained stage-2 model) is embedded
into a single kernel.py as base64 payloads. At runtime the kernel writes the
repo layout under WORK/app, symlinks the competition data as app/data (so the
modules' default paths resolve), and runs max_class1_exp/predict_test.py on
the mounted test.parquet. The molecule-key cache (RDKit tautomer pass over
~340k train SMILES) is rebuilt from scratch inside the kernel, exactly like
`common.ensure_cache` does locally.

Usage (from the repo root):
    uv run python scripts/build_kernel.py [--kernel-dir ../kernels/casmi26-stage2-sub]

The output dir gets kernel.py + kernel-metadata.json and is pushed with
POST /kernels/push {"kernel_dir": ...} (relative to the omac workdir).
"""

import argparse
import base64
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

# repo-relative path -> runtime path inside WORK/app
PAYLOADS = {
    "dataset-creation/common.py": "dataset-creation/common.py",
    "dataset-creation/make_difficulty1.py": "dataset-creation/make_difficulty1.py",
    "dataset-creation/dataloader.py": "dataset-creation/dataloader.py",
    "dataset-creation/cache_inchikey.py": "dataset-creation/cache_inchikey.py",
    "max_class1_exp/spectra.py": "max_class1_exp/spectra.py",
    "max_class1_exp/library.py": "max_class1_exp/library.py",
    "max_class1_exp/stage1.py": "max_class1_exp/stage1.py",
    "max_class1_exp/stage2.py": "max_class1_exp/stage2.py",
    "max_class1_exp/predict_test.py": "max_class1_exp/predict_test.py",
    "max_class1_exp/out/difficulty1_stage2_model.joblib":
        "max_class1_exp/out/difficulty1_stage2_model.joblib",
    "src/enveda_casmi26/__init__.py": "src/enveda_casmi26/__init__.py",
    "src/enveda_casmi26/pipeline.py": "src/enveda_casmi26/pipeline.py",
    "src/enveda_casmi26/tracking.py": "src/enveda_casmi26/tracking.py",
    "src/enveda_casmi26/fragmentation.py": "src/enveda_casmi26/fragmentation.py",
}

TEMPLATE = '''#!/usr/bin/env python
"""Kaggle kernel: stage-2 re-ranker submission for Enveda CASMI 2026.

Class-1 pipeline (library search): candidates = train molecules within
+-10 ppm of the query mass, re-ranked by the trained stage-2 model
(HistGradientBoosting over entropy/cosine/neutral-loss features), padded
with mass-nearest structures to 25 guesses per molecule.

Generated by scripts/build_kernel.py -- do not edit by hand. The pipeline
modules and the model are embedded as base64 below and unpacked to
WORK/app at runtime; then predict_test.py runs on the mounted test.parquet
and writes WORK/submission.csv.

Smoke test locally:
    KERNEL_WORK=/tmp/kw KERNEL_COMP_DIR=data \\
        python kernels/casmi26-stage2-sub/kernel.py
"""
import base64
import glob
import os
import sys
import time
from pathlib import Path

WORK = Path(os.environ.get("KERNEL_WORK", "/kaggle/working"))
COMP = os.environ.get("KERNEL_COMP_DIR")
T0 = time.time()


def log(msg):
    print(msg, flush=True)


def find(name):
    hits = glob.glob(f"/kaggle/input/**/{{name}}", recursive=True)
    return sorted(hits, key=len)[0] if hits else None


PAYLOADS = {{
{payloads}
}}


def main():
    log(f"[kernel] working dir: {{WORK}}")
    if COMP is None:
        test_path = find("test.parquet")
        if test_path is None:
            raise SystemExit("test.parquet not found under /kaggle/input")
        comp = str(Path(test_path).parent)
    else:
        comp = COMP
    train = os.path.join(comp, "train.parquet")
    test = os.path.join(comp, "test.parquet")
    log(f"[kernel] competition data: {{comp}}")

    app = WORK / "app"
    for rel, payload in PAYLOADS.items():
        p = app / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(base64.b64decode(payload))
    log(f"[kernel] unpacked {{len(PAYLOADS)}} files to {{app}}")

    data = app / "data"
    if not data.exists():
        os.symlink(comp, data)          # common.TRAIN & friends resolve like locally

    # Kaggle's image ships no RDKit: the molecule-key cache is then built from
    # the train columns inchikey14 + molecular_formula (validated locally:
    # MRR@25 0.709 vs 0.707 with the tautomer cache). With RDKit present the
    # faithful tautomer-canonical cache (common.ensure_cache) builds on the fly.
    try:
        if os.environ.get("KERNEL_NO_RDKIT") == "1":
            raise ImportError("forced by KERNEL_NO_RDKIT")
        import rdkit  # noqa: F401
        log("[kernel] rdkit available: using the tautomer-canonical key cache")
    except ImportError:
        log("[kernel] no rdkit: building the inchikey14 key cache (RDKit-free)")
        sys.path.insert(0, str(app / "dataset-creation"))
        from cache_inchikey import build_inchikey_cache
        build_inchikey_cache(train, app / "dataset-creation" / "out" / "cache")

    sys.path.insert(0, str(app / "max_class1_exp"))
    import predict_test
    sys.argv = ["predict_test",
                "--train", train, "--test", test,
                "--model", str(app / "max_class1_exp" / "out"
                               / "difficulty1_stage2_model.joblib"),
                "--out", str(WORK / "submission.csv"),
                "--diag", str(WORK / "test_stage2_diag.parquet")]
    predict_test.main()

    import pandas as pd
    sub = pd.read_csv(WORK / "submission.csv")
    n_slots = sub["smiles"].str.count(";") + 1
    log(f"[kernel] submission.csv: {{len(sub)}} molecules, slots min {{n_slots.min()}} "
        f"/ median {{n_slots.median():.0f}} / max {{n_slots.max()}}")
    log(f"[kernel] done in {{time.time() - T0:.0f}}s")


if __name__ == "__main__":
    main()
'''

METADATA = '''{{
  "id": "{username}/casmi26-stage2-sub",
  "title": "casmi26-stage2-sub",
  "code_file": "kernel.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": false,
  "enable_tpu": false,
  "enable_internet": false,
  "dataset_sources": [],
  "competition_sources": ["enveda-CASMI26-molecule-id-mass-spectra"],
  "kernel_sources": []
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kernel-dir", type=Path,
                        default=PROJECT_ROOT.parent / "kernels" / "casmi26-stage2-sub",
                        help="output dir (kernel.py + kernel-metadata.json)")
    parser.add_argument("--username", default="mmaxdietsch", help="Kaggle username for the id")
    args = parser.parse_args()

    lines, total = [], 0
    for src, rel in PAYLOADS.items():
        blob = base64.b64encode((PROJECT_ROOT / src).read_bytes()).decode()
        total += len(blob)
        lines.append(f'    "{rel}": (\n')
        # wrap the base64 at 96 chars to keep the file diff-able
        for i in range(0, len(blob), 96):
            lines.append(f'        "{blob[i:i + 96]}"\n')
        lines.append('    ),\n')
    kernel = TEMPLATE.format(payloads="".join(lines))
    args.kernel_dir.mkdir(parents=True, exist_ok=True)
    (args.kernel_dir / "kernel.py").write_text(kernel)
    (args.kernel_dir / "kernel-metadata.json").write_text(
        METADATA.format(username=args.username))
    print(f"wrote {args.kernel_dir}/kernel.py ({len(kernel) / 1024:.0f} KiB, "
          f"payloads {total / 1024:.0f} KiB) and kernel-metadata.json")


if __name__ == "__main__":
    main()
